import { test, expect } from '@playwright/test';
import { readFile, mkdir } from 'node:fs/promises';
import { bootEditorWithCaptions } from './support/editorBoot';

test('premium styles preview Gujarati and Hindi with narration motion', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const bytes = await readFile(new URL('./fixtures/sample-with-audio.mp4', import.meta.url));
  const words = ['તમારા', 'કૅપ્શન', 'સરસ', 'દેખાશે', 'आपके', 'कैप्शन', 'शानदार', 'दिखेंगे'];
  const document = { sections: [{ kind: 'main', segments: [{ lines: [{ words: words.map((text, i) => ({ text, start: i * 0.4, end: (i + 1) * 0.4 })) }] }] }] };
  await bootEditorWithCaptions(page, bytes, document);
  await page.getByRole('tab', { name: 'Templates', exact: true }).click();
  const originalWords = await page.evaluate(() => window.__tscapsE2E!.documentWords().map(word => word.text));
  const languages = page.getByRole('group', { name: 'Caption preview language' });
  await languages.getByRole('button', { name: 'ગુજરાતી Gujarati' }).click();
  await expect(languages.getByRole('button', { name: 'ગુજરાતી Gujarati' })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('button', { name: /View all 58/ }).click();
  await expect(page.locator('[class*=tscaps-preview-premium-] [lang=gu]')).toHaveCount(58);
  await page.getByPlaceholder('Search templates').fill('Crazy');
  const crazy = page.getByRole('button', { name: 'Crazy', exact: true });
  await expect(crazy.locator('[lang=gu]')).toContainText('તમારા');
  await crazy.hover();
  const sample = crazy.locator('[lang=gu]');
  const before = await sample.getAttribute('style');
  await expect.poll(() => sample.getAttribute('style')).not.toBe(before);
  await crazy.click();
  await expect(crazy).toHaveAttribute('aria-pressed', 'true');
  await page.evaluate(() => document.fonts.ready);
  expect(await page.evaluate(() => document.fonts.check('700 32px "Noto Sans Gujarati Variable"', 'કૅપ્શન'))).toBe(true);
  await mkdir('/tmp/reelstudio-caption-languages', { recursive: true });
  await page.screenshot({ path: '/tmp/reelstudio-caption-languages/gujarati.png' });
  await languages.getByRole('button', { name: 'हिन्दी Hindi' }).click();
  await expect(crazy.locator('[lang=hi]')).toContainText('आपके');
  await crazy.hover();
  const hindi = crazy.locator('[lang=hi]');
  const hindiBefore = await hindi.getAttribute('style');
  await expect.poll(() => hindi.getAttribute('style')).not.toBe(hindiBefore);
  await page.screenshot({ path: '/tmp/reelstudio-caption-languages/hindi.png' });
  expect(await page.evaluate(() => window.__tscapsE2E!.documentWords().map(word => word.text))).toEqual(originalWords);
  await page.getByPlaceholder('Search templates').fill('');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(languages).toBeVisible();
  await languages.getByRole('button', { name: 'ગુજરાતી Gujarati' }).click();
  await expect(languages.getByRole('button', { name: 'ગુજરાતી Gujarati' })).toHaveAttribute('aria-pressed', 'true');
  await page.screenshot({ path: '/tmp/reelstudio-caption-languages/mobile.png' });
  expect(errors).toEqual([]);
});
