import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { bootEditorWithCaptions } from './support/editorBoot';

test('creative edits preview, export with audio, and open as a new caption project', async ({ page }) => {
  const bytes = await readFile(new URL('./fixtures/sample-with-audio.mp4', import.meta.url));
  const document = JSON.parse(await readFile(new URL('./fixtures/document.json', import.meta.url), 'utf8'));
  test.setTimeout(45000);
  await bootEditorWithCaptions(page, bytes, document);
  await page.getByRole('tab', { name: 'Creative', exact: true }).click();
  await page.getByRole('button', { name: 'Open Creative Studio' }).click();
  const dialog = page.getByRole('dialog', { name: 'Creative Studio', exact: true });
  await expect(dialog.getByRole('button', { name: 'Preview', exact: true })).toBeEnabled();
  const original = await dialog.locator('canvas').evaluate(c => (c as HTMLCanvasElement).toDataURL());
  await dialog.getByRole('button', { name: 'Noir', exact: true }).click();
  await dialog.getByRole('textbox', { name: 'Text', exact: true }).fill('ReelStudio test');
  await dialog.getByRole('combobox').selectOption('pulse');
  await dialog.getByRole('textbox', { name: 'End value' }).fill('2');
  await dialog.getByRole('textbox', { name: 'End value' }).press('Enter');
  await dialog.evaluate(el => { el.scrollTop = 0; });
  await dialog.screenshot({ path: test.info().outputPath('creative-desktop.png') });
  await expect.poll(() => dialog.locator('canvas').evaluate(c => (c as HTMLCanvasElement).toDataURL())).not.toBe(original);
  await dialog.getByRole('button', { name: 'Render edited reel' }).click();
  await expect(dialog.getByRole('button', { name: 'Download reel' })).toBeVisible({ timeout: 20000 });
  const downloadPromise = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Download reel' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toMatch(/-reelstudio\.(mp4|webm)$/);
  const output = await readFile((await download.path())!);
  expect(output.length).toBeGreaterThan(1000);
  const decoded = await page.evaluate(async (array) => {
    const blob = new Blob([new Uint8Array(array)]);
    const video = window.document.createElement('video');
    const url = URL.createObjectURL(blob);
    video.src = url;
    await new Promise<void>((resolve, reject) => { video.onloadeddata = () => resolve(); video.onerror = () => reject(new Error('Cannot decode export')); });
    const result = { width: video.videoWidth, height: video.videoHeight };
    const context = new AudioContext();
    const audio = await context.decodeAudioData(await blob.arrayBuffer());
    await context.close(); URL.revokeObjectURL(url);
    return { ...result, audioLength: audio.length };
  }, Array.from(output));
  expect(decoded.width).toBeGreaterThan(0);
  expect(decoded.audioLength).toBeGreaterThan(0);
  await dialog.getByRole('button', { name: 'Add captions in a new project' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('dialog', { name: 'Start your video' })).toBeVisible();
});

test('mobile music, silence analysis, speed and canceled export', async ({ page }) => {
  test.setTimeout(45000);
  await page.setViewportSize({ width: 390, height: 844 });
  const bytes = await readFile(new URL('./fixtures/sample-with-audio.mp4', import.meta.url));
  const document = JSON.parse(await readFile(new URL('./fixtures/document.json', import.meta.url), 'utf8'));
  await bootEditorWithCaptions(page, bytes, document);
  await page.getByRole('tab', { name: 'Creative', exact: true }).click();
  await page.getByRole('button', { name: 'Open Creative Studio' }).click();
  const dialog = page.getByRole('dialog', { name: 'Creative Studio', exact: true });
  await expect(dialog.getByRole('button', { name: 'Preview', exact: true })).toBeEnabled();
  // A real WAV exercises the music decoder and mixing path without network dependencies.
  const samples = 44100;
  const wav = Buffer.alloc(44 + samples * 2);
  wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8);
  wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
  wav.writeUInt32LE(44100, 24); wav.writeUInt32LE(88200, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34);
  wav.write('data', 36); wav.writeUInt32LE(samples * 2, 40);
  for (let i = 0; i < samples; i++) wav.writeInt16LE(Math.round(Math.sin(i * 2 * Math.PI * 440 / 44100) * 8000), 44 + i * 2);
  await dialog.locator('input[type=file][accept="audio/*"]').setInputFiles({ name: 'music.wav', mimeType: 'audio/wav', buffer: wav });
  await expect(dialog.getByText('music.wav', { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: 'Detect & remove silences' }).click();
  await expect(dialog.getByRole('button', { name: 'Detect & remove silences' })).toBeEnabled({ timeout: 15000 });
  await dialog.getByRole('textbox', { name: 'Speed value' }).fill('0.5');
  await dialog.getByRole('textbox', { name: 'Speed value' }).press('Enter');
  await dialog.getByLabel('Beat jump cuts', { exact: true }).check();
  await dialog.evaluate(el => { el.scrollTop = 0; });
  await dialog.screenshot({ path: test.info().outputPath('creative-mobile.png') });
  expect(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await dialog.getByRole('button', { name: 'Render edited reel' }).click();
  await dialog.getByRole('button', { name: 'Cancel export' }).click();
  await expect(dialog.getByRole('button', { name: 'Render edited reel' })).toBeEnabled();
  await expect(dialog.getByRole('button', { name: 'Download reel' })).not.toBeVisible();
  await dialog.getByRole('textbox', { name: 'Speed value' }).fill('2');
  await dialog.getByRole('textbox', { name: 'Speed value' }).press('Enter');
  await dialog.getByRole('textbox', { name: 'Original audio value' }).fill('0');
  await dialog.getByRole('textbox', { name: 'Original audio value' }).press('Enter');
  await dialog.getByRole('button', { name: 'Render edited reel' }).click();
  await expect(dialog.getByRole('button', { name: 'Download reel' })).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await dialog.getByRole('button', { name: 'Download reel' }).click();
  const download = await downloadPromise;
  const output = await readFile((await download.path())!);
  const audioStats = await page.evaluate(async array => {
    const context = new AudioContext();
    const audio = await context.decodeAudioData(new Uint8Array(array).buffer);
    const samples = audio.getChannelData(0);
    const rms = Math.sqrt(samples.reduce((sum, value) => sum + value * value, 0) / samples.length);
    await context.close();
    return { rms, duration: audio.duration };
  }, Array.from(output));
  // Muted source: non-silent output must come from the uploaded music.
  expect(audioStats.rms).toBeGreaterThan(0.005);
  expect(audioStats.duration).toBeLessThan(1.5);
});
